/**
 * The parity runner for scenarios that need documents, notes and links to exist beforehand. It is the stock [ParityHarness]
 * procedure (two identically seeded databases, one reached through a real MCP client/server pair and one through
 * `POST /api/v1/ops/{tool}` with bearer auth, both under the scenario token; byte-equal bodies once the request id is replaced;
 * equal database snapshots; literal status oracles) with one extra seeding step ([DocsParityCase.docs]) and one extra
 * normalization: the services generate document, note and link ids at seed time, so the n-th seeded id of each leg is mapped to
 * the token `<Sn>` and ids generated by the call under test are numbered `<Gn>` by first appearance. The stock harness knows
 * only ids chosen by the scenario, and is not edited by this item.
 */
internal class DocsParityRunner(
    private val registry: ToolRegistry
) {
    private class Leg(
        val db: SqliteTestDatabase,
        val dir: Path,
        val rig: EventLogRig,
        val seedIds: List<UUID>
    ) : AutoCloseable {
        override fun close() {
            runCatching { db.close() }
            runCatching { dir.toFile().deleteRecursively() }
        }
    }

    private fun openLeg(case: DocsParityCase): Leg {
        val db = SqliteTestDatabase.open(clock = PARITY_CLOCK)
        val dir = Files.createTempDirectory("docs-parity-leg-")
        try {
            val rig = EventLogRig.build(db, dir, clock = PARITY_CLOCK)
            val ids =
                runBlocking {
                    case.scenario.seed(ParitySeeder(db.repositoryProvider().workItemRepository()))
                    val seeder = DocSeeder(rig.ctx, db.repositoryProvider())
                    case.docs(seeder)
                    seeder.finish()
                    seeder.generatedIds
                }
            return Leg(db, dir, rig, ids)
        } catch (e: Throwable) {
            runCatching { db.close() }
            runCatching { dir.toFile().deleteRecursively() }
            throw e
        }
    }

    private class RestResult(
        val status: Int,
        val body: String,
        val reqIdHeader: String?
    )

    private fun runRest(
        leg: Leg,
        s: ParityScenario
    ): RestResult {
        var result: RestResult? = null
        testApplication {
            application { installParityRestApp(leg.rig, parityAuthConfig(s.token), registry) }
            val response =
                client.post("/api/v1/ops/${s.tool}") {
                    header(HttpHeaders.Authorization, "Bearer ${s.token.raw}")
                    contentType(ContentType.Application.Json)
                    setBody(s.arguments)
                }
            val text = response.bodyAsText()
            assertParityBodyConforms(text, "${s.name}: REST body", s.arguments)
            result = RestResult(response.status.value, text, response.headers["X-Req-Id"])
        }
        return checkNotNull(result) { "REST leg produced no response" }
    }

    /** A stamp on the fixed clock is compared exactly; a stamp some store takes from the wall clock instead is masked. */
    private fun normalize(
        body: String,
        reqId: String
    ): String {
        val marker = "\"reqId\":\"$reqId\""
        assertTrue(marker in body, "body carries its reqId marker: $body")
        val fixed = PARITY_NOW.toString()
        return body.replace(marker, "\"reqId\":\"<REQ>\"").replace(TIMESTAMP) { match ->
            val value = match.groupValues[2]
            if (value == fixed) {
                match.value
            } else {
                Instant.parse(value)
                "\"${match.groupValues[1]}\":\"<WALL>\""
            }
        }
    }

    private fun dashed(hex: String): String =
        "${hex.substring(0, 8)}-${hex.substring(8, 12)}-${hex.substring(12, 16)}-${hex.substring(16, 20)}-${hex.substring(20)}"

    /** The lowercase dashed UUIDs a cell carries: a dashed UUID inside text, or a whole-cell 32-hex blob. */
    private fun uuidsIn(cell: Any?): List<String> =
        when {
            cell !is String -> emptyList()
            HEX_BLOB.matches(cell) -> listOf(dashed(cell))
            else -> UUID_TEXT.findAll(cell).map { it.value.lowercase() }.toList()
        }

    /** The ids the scenario chose: every UUID of the seeded work items, plus those named in the arguments. */
    private fun fixedIds(
        rawBefore: Map<String, List<Map<String, Any?>>>,
        arguments: String
    ): Set<String> =
        buildSet {
            for (row in rawBefore.getValue("work_items")) for (cell in row.values) addAll(uuidsIn(cell))
            addAll(UUID_TEXT.findAll(arguments).map { it.value.lowercase() })
        }

    /**
     * [raw] without noise columns, with every id replaced: a fixed id stays, a seeded id becomes `<Sn>`, an id generated by the
     * call becomes `<Gn>` (numbered by first appearance in the events table by seq, then in [body]), any other `<GEN>`. Returns
     * the tokenized body and tables (non-event rows re-sorted after tokenization).
     */
    private fun view(
        raw: Map<String, List<Map<String, Any?>>>,
        body: String,
        fixed: Set<String>,
        seed: Map<String, String>
    ): Pair<String, Map<String, List<Map<String, Any?>>>> {
        val projected = ParityHarness.project(raw)
        val generated = LinkedHashMap<String, String>()

        fun note(uuid: String) {
            if (uuid !in fixed && uuid !in seed && uuid !in generated) generated[uuid] = "<G${generated.size + 1}>"
        }
        for (row in projected.getValue("events")) for (cell in row.values) uuidsIn(cell).forEach(::note)
        UUID_TEXT.findAll(body).forEach { note(it.value.lowercase()) }

        fun swap(uuid: String): String {
            val lower = uuid.lowercase()
            return when {
                lower in fixed -> uuid
                else -> seed[lower] ?: generated[lower] ?: "<GEN>"
            }
        }

        fun apply(cell: Any?): Any? =
            when {
                cell !is String -> cell
                HEX_BLOB.matches(cell) -> if (dashed(cell) in fixed) cell else swap(dashed(cell))
                else -> UUID_TEXT.replace(cell) { swap(it.value) }
            }
        val tables =
            projected.mapValues { (table, rows) ->
                val mapped = rows.map { row -> row.mapValues { apply(it.value) } }
                if (table == "events") mapped else mapped.sortedBy { it.toString() }
            }
        return UUID_TEXT.replace(body) { swap(it.value) } to tables
    }

    fun run(case: DocsParityCase): ParityOutcome {
        val s = case.scenario
        val restLeg = openLeg(case)
        val mcpLeg =
            try {
                openLeg(case)
            } catch (e: Throwable) {
                restLeg.close()
                throw e
            }
        try {
            assertEquals(restLeg.seedIds.size, mcpLeg.seedIds.size, "${s.name}: both legs generated the same number of seed ids")
            val restSeed = restLeg.seedIds.mapIndexed { i, id -> id.toString().lowercase() to "<S${i + 1}>" }.toMap()
            val mcpSeed = mcpLeg.seedIds.mapIndexed { i, id -> id.toString().lowercase() to "<S${i + 1}>" }.toMap()

            val restRawBefore = ParityHarness.rawTables(restLeg.db.jdbcUrl)
            val mcpRawBefore = ParityHarness.rawTables(mcpLeg.db.jdbcUrl)
            val fixed = fixedIds(restRawBefore, s.arguments)
            val restBefore = view(restRawBefore, "", fixed, restSeed).second
            val mcpBefore = view(mcpRawBefore, "", fixed, mcpSeed).second
            assertEquals(restBefore, mcpBefore, "${s.name}: the two legs must start from identical seeded databases")
            assertTrue(restBefore.getValue("work_items").isNotEmpty(), "${s.name}: the item tree is seeded")

            val rest = runRest(restLeg, s)
            val mcp =
                runBlocking {
                    callMcp(
                        mcpLeg.rig.composition.toolContext,
                        registry,
                        { parityAccess(s.token) },
                        s.tool,
                        Json.parseToJsonElement(s.arguments).jsonObject
                    )
                }

            val restBody = Json.parseToJsonElement(rest.body).jsonObject
            val restReqId =
                assertNotNull(
                    restBody["meta"]
                        ?.jsonObject
                        ?.get("reqId")
                        ?.jsonPrimitive
                        ?.content,
                    "${s.name}: REST meta.reqId"
                )
            assertEquals(restReqId, rest.reqIdHeader, "${s.name}: X-Req-Id equals the body's meta.reqId")
            val mcpReqId =
                assertNotNull(
                    mcp.structured["meta"]
                        ?.jsonObject
                        ?.get("reqId")
                        ?.jsonPrimitive
                        ?.content,
                    "${s.name}: MCP meta.reqId"
                )
            assertEquals(mcpReqId, mcp.reqIdMeta, "${s.name}: _meta.reqId equals the body's meta.reqId")
            assertNotEquals(restReqId, mcpReqId, "${s.name}: each call gets its own reqId")

            val (restNorm, restAfter) =
                view(ParityHarness.rawTables(restLeg.db.jdbcUrl), normalize(rest.body, restReqId), fixed, restSeed)
            val (mcpNorm, mcpAfter) =
                view(ParityHarness.rawTables(mcpLeg.db.jdbcUrl), normalize(mcp.structured.toString(), mcpReqId), fixed, mcpSeed)
            assertEquals(mcpNorm, restNorm, "${s.name}: body parity between MCP and REST")

            val ok = restBody["ok"]?.jsonPrimitive?.boolean ?: error("${s.name}: body has no ok flag")
            assertEquals(!ok, mcp.isError, "${s.name}: MCP isError is the negation of ok")
            val code =
                restBody["error"]
                    ?.jsonObject
                    ?.get("code")
                    ?.jsonPrimitive
                    ?.content
            assertEquals(s.expectCode, code, "${s.name}: error code in $restNorm")
            assertEquals(s.expectStatus, rest.status, "${s.name}: REST status in $restNorm")
            if (code != null) {
                assertEquals(
                    ErrorCode.entries.single { it.wire == code }.httpStatus,
                    rest.status,
                    "${s.name}: REST status equals the error code's catalog status"
                )
            } else {
                assertEquals(200, rest.status, "${s.name}: an ok body is 200")
            }
            for (needle in s.expectContains) assertTrue(needle in restNorm, "${s.name}: body must contain $needle but was $restNorm")
            for (needle in s.expectAbsent) assertFalse(needle in restNorm, "${s.name}: body must not contain $needle but was $restNorm")

            for (table in restAfter.keys) {
                assertEquals(restAfter.getValue(table), mcpAfter.getValue(table), "${s.name}: $table snapshot parity between REST and MCP")
            }
            val changed = restAfter != restBefore
            s.expectDbChanged?.let { assertEquals(it, changed, "${s.name}: database changed") }
            return ParityOutcome(rest.status, restNorm, restAfter, changed)
        } finally {
            restLeg.close()
            mcpLeg.close()
        }
    }

    private companion object {
        val TIMESTAMP = Regex("\"(createdAt|modifiedAt)\":\"([^\"]*)\"")
        val UUID_TEXT = Regex("[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}")
        val HEX_BLOB = Regex("[0-9a-f]{32}")
    }
}

/**
 * Independent tests (test-author seat, item 8e99f1e2, Q25) for `docs_read` / `docs_write`, scenarios S1-S22 of the frozen
 * test-plan that have a parity half. Every catalog scenario of [DocsParityScenarios] runs through [DocsParityRunner] (the same
 * arguments over MCP and over `POST /api/v1/ops/{tool}`, byte-equal bodies, equal database snapshots, literal status oracles); the
 * tests below read the outcome of selected runs for the facts the catalog's substring checks cannot state (stored rows, event
 * rows). The MCP-only halves (bodyFromFile, size caps, idempotent replay, paging cursors, attribution, removal of the 3.x
 * surface) are in `DocsToolsBehaviorTest`.
 *
 * Oracles: the response-envelope spec (statuses, shapes), the `DocumentService` KDoc (hash of the LF body, created iff version 1,
 * archive/adopt reasons, caps), the frozen task-scope decisions D1-D9, and the document event names of the event contract
 * (`document.created`, `document.updated`, `document.archived`, `document.deleted`). Generated ids reach this file as tokens
 * (`<S1>` seeded, `<G1>` generated by the call).
 */
@Timeout(value = 900, unit = TimeUnit.SECONDS)
class DocsParityTest {
    private val registry = ToolRegistry(buildToolSpecs())
    private val runner = DocsParityRunner(registry)

    private fun case(name: String): DocsParityCase = DocsParityScenarios.cases.single { it.scenario.name == name }

    private fun eventTypes(o: ParityOutcome): List<Any?> = o.snapshot.getValue("events").map { it["type"] }

    // ------------------------------------------------------------------ the catalog

    @TestFactory
    fun `every docs scenario agrees across MCP and REST and meets its literal oracle`(): List<DynamicTest> =
        DocsParityScenarios.cases.map { c -> DynamicTest.dynamicTest(c.scenario.name) { runner.run(c) } }

    @Test
    fun `the catalog names are unique so a failure points at one scenario`() {
        val names = DocsParityScenarios.cases.map { it.scenario.name }
        assertEquals(
            names.size,
            names.toSet().size,
            "duplicate scenario names: ${names.groupingBy { it }.eachCount().filter { it.value > 1 }}"
        )
    }

    @Test
    fun `the catalog gives every docs select and op a happy and a restricted-scope forbidden scenario`() {
        val docsOnly = ToolRegistry(buildToolSpecs().filter { it.name.startsWith("docs_") })
        assertEquals(
            setOf(
                "docs_read" to "get",
                "docs_read" to "list",
                "docs_read" to "history",
                "docs_read" to "links",
                "docs_write" to "upsert",
                "docs_write" to "archive",
                "docs_write" to "unarchive",
                "docs_write" to "delete",
                "docs_write" to "attach",
                "docs_write" to "detach"
            ),
            ParityCoverage.members(docsOnly).toSet()
        )
        assertEquals(emptyList(), ParityCoverage.missing(docsOnly, DocsParityScenarios.scenarios, DocsParityScenarios.exemptions))
        assertEquals(emptyList(), ParityCoverage.stale(docsOnly, DocsParityScenarios.scenarios))
        assertTrue(DocsParityScenarios.exemptions.isEmpty(), "no scope exemption: every docs member names a document under a root")
    }

    @Test
    fun `the production catalog registers the docs scenarios`() {
        assertTrue(ProductionParity.scenarios.containsAll(DocsParityScenarios.scenarios), "every docs scenario is registered")
        assertTrue(ProductionParity.exemptions.containsAll(DocsParityScenarios.exemptions), "every docs exemption is registered")
    }

    // ------------------------------------------------------------------ stored rows and events

    @Test
    fun `S1 a created plan adds one document one version and one document created event`() {
        val o = runner.run(case("S1 docs_write upsert happy"))
        assertEquals(4, o.snapshot.getValue("documents").size, "three seeded documents and the new one")
        assertEquals(4, o.snapshot.getValue("document_versions").size, "one version per document")
        assertEquals(4, eventTypes(o).count { it == "document.created" }, "three seeded and one new")
        assertEquals(0, eventTypes(o).count { it == "document.updated" })
    }

    @Test
    fun `S2 a re-upsert adds a version row and one document updated event and keeps one document row`() {
        val o = runner.run(case("S2 re-upsert with the current expectedVersion makes version 2"))
        assertEquals(3, o.snapshot.getValue("documents").size, "no new document row")
        assertEquals(4, o.snapshot.getValue("document_versions").size, "three version-1 rows and the new version 2")
        assertEquals(1, eventTypes(o).count { it == "document.updated" })
    }

    @Test
    fun `S10 a stale expectedVersion adds no version row and no event`() {
        val o = runner.run(case("S10 stale expectedVersion is version_conflict and writes nothing"))
        assertEquals(3, o.snapshot.getValue("document_versions").size)
        assertEquals(0, eventTypes(o).count { it == "document.updated" })
        assertFalse(o.dbChanged)
    }

    @Test
    fun `S5 archive records one document archived event and unarchive of an archived page restores it`() {
        val archived = runner.run(case("S5 docs_write archive happy"))
        assertEquals(1, eventTypes(archived).count { it == "document.archived" })
        assertEquals(3, archived.snapshot.getValue("documents").size, "archive keeps the row")
    }

    @Test
    fun `S6 a deleted page leaves no document row and no version row of its own and records one document deleted event`() {
        val o = runner.run(case("S6 docs_write delete happy"))
        assertEquals(2, o.snapshot.getValue("documents").size)
        assertEquals(2, o.snapshot.getValue("document_versions").size)
        assertEquals(1, eventTypes(o).count { it == "document.deleted" })
    }

    @Test
    fun `S6 deleting a plan that a note links to keeps the note link as a dangling row`() {
        val before = runner.run(case("S8 links outgoing returns what the document links to"))
        val after = runner.run(case("S6 delete of a plan that a note links to succeeds"))
        // the note's reference to alpha-plan outlives the document (the outgoing alpha-plan link goes with its source)
        assertEquals(2, before.snapshot.getValue("links").size)
        assertEquals(1, after.snapshot.getValue("links").size, "only the note's now dangling link remains")
    }

    @Test
    fun `S7 an attachment is one link row and a second attach adds none`() {
        val first = runner.run(case("S7 docs_write attach happy"))
        assertEquals(1, first.snapshot.getValue("links").size)
        val twice = runner.run(case("S7 attach twice in one batch succeeds twice"))
        assertEquals(1, twice.snapshot.getValue("links").size, "the second attach returns the existing link")
    }

    @Test
    fun `S7 detach removes only the attachment`() {
        val o = runner.run(case("S7 docs_write detach happy"))
        assertEquals(0, o.snapshot.getValue("links").size)
        assertEquals(3, o.snapshot.getValue("documents").size)
    }

    @Test
    fun `S11 refused writes against an adopted document leave the document and its adoption link`() {
        for (name in listOf(
            "S11 upsert of an adopted document is duplicate",
            "S11 delete of an adopted document is invalid_request naming the adoption"
        )) {
            val o = runner.run(case(name))
            assertEquals(3, o.snapshot.getValue("documents").size, name)
            assertEquals(1, o.snapshot.getValue("links").size, "$name: the adoption link stays")
            assertEquals(0, eventTypes(o).count { it == "document.updated" || it == "document.deleted" }, name)
        }
    }

    @Test
    fun `S17 a rejected slug stores no document and a valid one stores exactly one`() {
        for (c in DocsParityScenarios.slugGuard.filter { it.scenario.name.startsWith("S17 upsert rejects") }) {
            val o = runner.run(c)
            assertEquals(3, o.snapshot.getValue("documents").size, "${c.scenario.name}: nothing stored")
        }
        for (c in DocsParityScenarios.slugGuard.filter { it.scenario.name.startsWith("S17 upsert accepts") }) {
            val o = runner.run(c)
            assertEquals(4, o.snapshot.getValue("documents").size, "${c.scenario.name}: one stored")
        }
    }

    @Test
    fun `S15 a forbidden call writes no event`() {
        for (c in DocsParityScenarios.scopeForbidden.filter { it.scenario.expectDbChanged == false }) {
            val before =
                runner
                    .run(case("S1 docs_read get happy"))
                    .snapshot
                    .getValue("events")
                    .size
            val after =
                runner
                    .run(c)
                    .snapshot
                    .getValue("events")
                    .size
            // both runs seed the same documents, so a forbidden call must leave exactly the seeded event rows
            assertEquals(before, after, "${c.scenario.name}: no event row beyond the seeded ones")
        }
    }
}
